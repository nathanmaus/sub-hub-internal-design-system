#!/usr/bin/env node
/*
 * build-assets.mjs: embeds the icon library and the logo lockups into the design system code,
 * so components/bundle.js works on its own in any project (no icons/ or assets/ folder to copy,
 * no CDN, no asset store).
 *
 *   node scripts/build-assets.mjs           rebuild after icons/ or assets/ change
 *   node scripts/build-assets.mjs --check   exit 1 if the bundle is out of date (for CI)
 *
 * Optional flags: --icons <dir> (default icons/), --assets <dir> (default assets/),
 * --bundle <file> (default components/bundle.js), --src <dir> (default components/).
 *
 * Writes:
 *   components/bundle.js            the ICON_SVG and LOGO_SRC blocks between @generated markers
 *   components/core/icon-data.js    the same icon map, as an ES module for the source files
 *   components/brand/logo-data.js   the same logo map, as an ES module for the source files
 *   icons/index.json                the icon name list
 *
 * Icons are SubHub Icon Library exports from Figma and are never edited here. This script only
 * trims the root <svg> tag (drops width and height so the glyph scales) and line breaks.
 */
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const flag = (name, dflt) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : dflt; };
const CHECK = args.includes("--check");
const ROOT = process.cwd();
const ICONS = path.resolve(ROOT, flag("--icons", "icons"));
const ASSETS = path.resolve(ROOT, flag("--assets", "assets"));
const BUNDLE = path.resolve(ROOT, flag("--bundle", "components/bundle.js"));
const SRC = path.resolve(ROOT, flag("--src", "components"));

function minifySvg(svg) {
  return svg
    .replace(/<\?xml[^>]*>/g, "")
    .replace(/\r?\n\s*/g, "")
    .replace(/^\s*<svg\b([^>]*)>/, (m, attrs) =>
      "<svg" + attrs.replace(/\s(width|height)="[^"]*"/g, "") + ">")
    .replace(/><\/(path|circle|rect|ellipse|line|polyline|polygon)>/g, "/>")
    .trim();
}

// Icons
const iconFiles = fs.readdirSync(ICONS).filter(f => f.endsWith(".svg"))
  .sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()));
if (!iconFiles.length) { console.error("No icons found in " + ICONS); process.exit(1); }
const icons = {};
for (const f of iconFiles) {
  const svg = minifySvg(fs.readFileSync(path.join(ICONS, f), "utf8"));
  if (!/viewBox="0 0 24 24"/.test(svg)) console.warn("! " + f + " is not on the 24px viewBox");
  icons[f.slice(0, -4)] = svg;
}
if (!icons.placeholder) { console.error("icons/placeholder.svg is required (it renders for unknown names)."); process.exit(1); }

// Logos: SVG preferred, PNG fallback, embedded as data URIs.
const LOGO_FILES = { dark: "logo-dark", light: "logo-light", amber: "logo-on-amber" };
const logos = {};
for (const [variant, base] of Object.entries(LOGO_FILES)) {
  const svgPath = path.join(ASSETS, base + ".svg"), pngPath = path.join(ASSETS, base + ".png");
  if (fs.existsSync(svgPath)) {
    logos[variant] = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(minifySvg(fs.readFileSync(svgPath, "utf8")));
  } else if (fs.existsSync(pngPath)) {
    logos[variant] = "data:image/png;base64," + fs.readFileSync(pngPath).toString("base64");
  } else { console.error("Missing logo file " + base + ".svg or .png in " + ASSETS); process.exit(1); }
}
logos.sand = logos.amber; // "sand" is the Internal system's name for the same lockup

const iconBlock = "const ICON_SVG = " + JSON.stringify(icons) + ";";
const logoBlock = "const LOGO_SRC = " + JSON.stringify(logos) + ";";
const stamp = iconFiles.length + " icons, " + Object.keys(LOGO_FILES).length + " logos. Generated by scripts/build-assets.mjs; do not edit by hand.";

function replaceBlock(text, name, body) {
  const re = new RegExp("(/\\* @generated:" + name + ":start[^*]*\\*/)[\\s\\S]*?(/\\* @generated:" + name + ":end \\*/)");
  if (!re.test(text)) throw new Error("Marker @generated:" + name + " not found in " + path.relative(ROOT, BUNDLE));
  return text.replace(re, (m, a, b) => "/* @generated:" + name + ":start " + stamp + " */\n" + body + "\n" + b);
}

const before = fs.readFileSync(BUNDLE, "utf8");
const after = replaceBlock(replaceBlock(before, "icons", iconBlock), "logos", logoBlock);

const header = "/* GENERATED by scripts/build-assets.mjs from %s. Do not edit by hand. */\n";
const iconModule = header.replace("%s", "icons/*.svg") + "export " + iconBlock + "\n";
const logoModule = header.replace("%s", "assets/logo-*") + "export " + logoBlock + "\n";
const iconDataPath = path.join(SRC, "core/icon-data.js");
const logoDataPath = path.join(SRC, "brand/logo-data.js");

const indexPath = path.join(ICONS, "index.json");
let index = {};
try { index = JSON.parse(fs.readFileSync(indexPath, "utf8")); } catch (e) { /* new index */ }
index.count = iconFiles.length;
index.icons = Object.keys(icons);
const indexText = JSON.stringify(index, null, 2) + "\n";

const outputs = [[BUNDLE, after], [iconDataPath, iconModule], [logoDataPath, logoModule], [indexPath, indexText]];
if (CHECK) {
  const stale = outputs.filter(([p, t]) => !fs.existsSync(p) || fs.readFileSync(p, "utf8") !== t).map(([p]) => path.relative(ROOT, p));
  if (stale.length) { console.error("Out of date: " + stale.join(", ") + ". Run node scripts/build-assets.mjs"); process.exit(1); }
  console.log("Up to date: " + stamp);
} else {
  for (const [p, t] of outputs) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, t); }
  console.log("Embedded " + stamp + " Bundle is " + Math.round(after.length / 1024) + " KB.");
}
